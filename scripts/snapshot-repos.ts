/**
 * Refreshes src/data/repoSnapshot.ts — the offline fallback for the Repos page —
 * with current data from the GitHub API. Run: npm run repos:snapshot
 * (set GITHUB_TOKEN for a higher rate limit; works without it).
 */
import { writeFileSync } from "node:fs";
import { CURATED_REPOS } from "../src/data/repos";
import { fetchReposByName } from "../src/lib/github";

const repos = await fetchReposByName(
  CURATED_REPOS.map((repo) => repo.fullName),
  { token: process.env.GITHUB_TOKEN },
);
const missing = CURATED_REPOS.filter((repo) => !repos[repo.fullName.toLowerCase()]).map((repo) => repo.fullName);
if (missing.length) {
  console.error(`Not found on GitHub (renamed or deleted?): ${missing.join(", ")}`);
  process.exit(1);
}

const body = `// Generated by scripts/snapshot-repos.ts on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
import type { RepoInfo } from "../lib/github";

export const REPO_SNAPSHOT_DATE = "${new Date().toISOString()}";

export const REPO_SNAPSHOT: Record<string, RepoInfo> = ${JSON.stringify(repos, null, 2)};
`;
writeFileSync(new URL("../src/data/repoSnapshot.ts", import.meta.url), body);
console.log(`Saved ${Object.keys(repos).length} repos.`);
